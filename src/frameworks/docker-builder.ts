/**
 * Dynamic Dockerfile Builder
 *
 * Generates framework-specific Dockerfiles by layering framework install
 * steps on top of the base sandbox Dockerfile. The generated Dockerfile
 * is written to a temp location and passed to `docker build`.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join } from "node:path";
import { homedir } from "node:os";
import type { FrameworkDefinition } from "./registry.js";

export interface FrameworkDockerfileOptions {
  /** Include the browser automation profile in the generated image. */
  browser?: boolean;
}

// ---------------------------------------------------------------------------
// Public API
// ---------------------------------------------------------------------------

/**
 * Generate a Dockerfile for a specific framework.
 * Reads the base Dockerfile and appends framework-specific layers.
 *
 * @returns The absolute path to the generated Dockerfile.
 */
export function generateFrameworkDockerfile(
  framework: FrameworkDefinition,
  baseDockerfilePath: string,
  opts: FrameworkDockerfileOptions = {},
): string {
  const baseContent = readFileSync(baseDockerfilePath, "utf8");

  // Split the base Dockerfile at the USER directive — we need to install
  // packages as root, then switch back to the non-root user.
  const lines = baseContent.split("\n");
  const userLineIdx = lines.findIndex((l) => /^USER\s+agent/i.test(l.trim()));

  if (userLineIdx === -1) {
    throw new Error(
      "Cannot find 'USER agent' directive in base Dockerfile. " +
      "Framework image generation requires the standard sandbox Dockerfile layout.",
    );
  }

  // Everything before USER agent (root context)
  const beforeUser = lines.slice(0, userLineIdx);
  // USER agent and everything after
  const afterUser = lines.slice(userLineIdx);

  const browserLayers = opts.browser ? buildBrowserLayers() : [];
  const frameworkLayers = buildFrameworkLayers(framework);

  const generated = [
    ...beforeUser,
    ...(browserLayers.length > 0
      ? [
          "",
          "# ---------------------------------------------------------------------------",
          "# Capability: browser automation (auto-generated by silo build --browser)",
          "# ---------------------------------------------------------------------------",
          ...browserLayers,
        ]
      : []),
    "",
    "# ---------------------------------------------------------------------------",
    `# Framework: ${framework.name} (auto-generated by silo build --framework${opts.browser ? " --browser" : ""})`,
    "# ---------------------------------------------------------------------------",
    ...frameworkLayers,
    "",
    ...afterUser,
  ].join("\n");

  // Write to ~/.silo/dockerfiles/<framework-id>[-browser]/Dockerfile
  const outDir = join(
    homedir(),
    ".silo",
    "dockerfiles",
    opts.browser ? `${framework.id}-browser` : framework.id,
  );
  if (!existsSync(outDir)) {
    mkdirSync(outDir, { recursive: true });
  }
  const outPath = join(outDir, "Dockerfile");
  writeFileSync(outPath, generated, "utf8");

  return outPath;
}

// ---------------------------------------------------------------------------
// Internal helpers
// ---------------------------------------------------------------------------

function buildFrameworkLayers(framework: FrameworkDefinition): string[] {
  const layers: string[] = [];

  // 1. System dependencies (apt-get)
  if (framework.install.systemDeps && framework.install.systemDeps.length > 0) {
    layers.push(
      `RUN apt-get update && apt-get install -y --no-install-recommends \\`,
      `        ${framework.install.systemDeps.join(" \\\n        ")} \\`,
      `    && rm -rf /var/lib/apt/lists/* \\`,
      `    && apt-get clean`,
    );
    layers.push("");
  }

  // 2. Framework install
  switch (framework.install.method) {
    case "pip": {
      const packages = framework.install.packages.join(" ");
      layers.push(
        `# Install ${framework.name} via pip`,
        `RUN pip install --no-cache-dir --break-system-packages ${packages}`,
      );
      break;
    }

    case "npm": {
      const packages = framework.install.packages
        .map((p) => `${p}@${framework.version}`)
        .join(" ");
      layers.push(
        `# Install ${framework.name} via npm`,
        `RUN npm install -g ${packages}`,
      );
      break;
    }

    case "custom": {
      if (framework.install.dockerSnippet) {
        layers.push(
          `# Install ${framework.name} (custom)`,
          framework.install.dockerSnippet,
        );
      }
      break;
    }
  }

  // 3. Environment variables
  if (framework.envVars && Object.keys(framework.envVars).length > 0) {
    layers.push("");
    layers.push(`# ${framework.name} environment variables`);
    for (const [key, val] of Object.entries(framework.envVars)) {
      layers.push(`ENV ${key}="${val}"`);
    }
  }

  // 4. Expose ports (for web UIs)
  if (framework.ports && framework.ports.length > 0) {
    layers.push("");
    layers.push(`# ${framework.name} ports`);
    for (const port of framework.ports) {
      layers.push(`EXPOSE ${port}`);
    }
  }

  return layers;
}

function buildBrowserLayers(): string[] {
  return [
    "# Install a browser runtime for Playwright/Puppeteer-style automation",
    "RUN apt-get update && apt-get install -y --no-install-recommends \\",
    "        chromium \\",
    "        fonts-liberation \\",
    "        xdg-utils \\",
    "    && rm -rf /var/lib/apt/lists/* \\",
    "    && apt-get clean",
    "",
    "# Route common browser executable names through a Docker-safe launcher",
    "RUN printf '%s\\n' \\",
    "        '#!/bin/sh' \\",
    "        'set -efu' \\",
    "        'set -- ${SILO_BROWSER_ARGS:-} \"$@\"' \\",
    "        'exec /usr/bin/chromium \"$@\"' \\",
    "    > /usr/local/bin/silo-chromium \\",
    "    && chmod 755 /usr/local/bin/silo-chromium \\",
    "    && ln -sf /usr/local/bin/silo-chromium /usr/local/bin/chromium \\",
    "    && ln -sf /usr/local/bin/silo-chromium /usr/local/bin/chromium-browser \\",
    "    && ln -sf /usr/local/bin/silo-chromium /usr/local/bin/google-chrome \\",
    "    && ln -sf /usr/local/bin/silo-chromium /usr/local/bin/chrome",
    "",
    "# Dedicated writable browser runfiles; mounted as tmpfs at runtime",
    "RUN mkdir -p /browser-cache /browser-profile /browser-downloads \\",
    "    && chown -R 1001:1001 /browser-cache /browser-profile /browser-downloads",
    "",
    "# Browser automation defaults. The browser binary lives in the read-only image.",
    'ENV SILO_BROWSER="1"',
    'ENV CHROME_BIN="/usr/local/bin/silo-chromium"',
    'ENV CHROMIUM_BIN="/usr/local/bin/silo-chromium"',
    'ENV BROWSER_EXECUTABLE_PATH="/usr/local/bin/silo-chromium"',
    'ENV PUPPETEER_EXECUTABLE_PATH="/usr/local/bin/silo-chromium"',
    'ENV PUPPETEER_SKIP_DOWNLOAD="true"',
    'ENV PUPPETEER_CACHE_DIR="/browser-cache/puppeteer"',
    'ENV PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD="1"',
    'ENV XDG_CACHE_HOME="/browser-cache"',
    'ENV XDG_CONFIG_HOME="/browser-profile"',
    'ENV SILO_BROWSER_PROFILE_DIR="/browser-profile"',
    'ENV SILO_BROWSER_DOWNLOADS_DIR="/browser-downloads"',
    'ENV SILO_BROWSER_ARGS="--no-sandbox --disable-setuid-sandbox --disable-dev-shm-usage --user-data-dir=/browser-profile"',
  ];
}

/**
 * Copy the base sandbox entrypoint.sh and Dockerfile into the generated
 * build context directory so `docker build` can access them.
 */
export function prepareFrameworkBuildContext(
  framework: FrameworkDefinition,
  sandboxDir: string,
  opts: FrameworkDockerfileOptions = {},
): { dockerfilePath: string; contextDir: string } {
  const outDir = join(
    homedir(),
    ".silo",
    "dockerfiles",
    opts.browser ? `${framework.id}-browser` : framework.id,
  );
  if (!existsSync(outDir)) {
    mkdirSync(outDir, { recursive: true });
  }

  // Copy entrypoint.sh to the generated context
  const entrypointSrc = join(sandboxDir, "entrypoint.sh");
  if (existsSync(entrypointSrc)) {
    const content = readFileSync(entrypointSrc, "utf8");
    writeFileSync(join(outDir, "entrypoint.sh"), content, { mode: 0o755 });
  }

  // Copy silo_callbacks/ to the generated context
  const callbacksDir = join(sandboxDir, "silo_callbacks");
  if (existsSync(callbacksDir)) {
    const destCallbacks = join(outDir, "silo_callbacks");
    if (!existsSync(destCallbacks)) {
      mkdirSync(destCallbacks, { recursive: true });
    }
    // Copy __init__.py (main callbacks module)
    const initSrc = join(callbacksDir, "__init__.py");
    if (existsSync(initSrc)) {
      const content = readFileSync(initSrc, "utf8");
      writeFileSync(join(destCallbacks, "__init__.py"), content);
    }
  }

  // Generate the framework Dockerfile
  const baseDockerfile = join(sandboxDir, "Dockerfile");
  const dockerfilePath = generateFrameworkDockerfile(framework, baseDockerfile, opts);

  return { dockerfilePath, contextDir: outDir };
}
